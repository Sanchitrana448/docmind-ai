"""Reproducible evaluation. Run: python eval/run_eval.py   (needs Tesseract)

Generates documents with known ground truth (seeded), runs them through the
real pipeline, and reports field accuracy and, more importantly, the silent
error rate: wrong values that were NOT sent to review. Writes RESULTS.md.
"""
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.pipeline import process_document  # noqa: E402
from app.samples import render_png  # noqa: E402

rng = random.Random(42)


def money(v: float) -> str:
    return f"${v:,.2f}"


def build_cases():
    cases = []  # (label, filename, bytes, truth_total, truth_date)
    for i in range(12):
        sub = round(rng.uniform(50, 4000), 2)
        total = round(sub * 1.1, 2)
        date = f"{rng.randint(1, 28):02d}/{rng.randint(1, 12):02d}/2026"
        text = (
            f"INVOICE\nInvoice Number: INV-2026-{rng.randint(1000, 9999)}\nFrom: Northwind Supplies Ltd\n"
            f"Invoice Date: {date}\nDue Date: 28/12/2026\nBill To: Beta Corp\n"
            f"Subtotal: {money(sub)}\nTotal: {money(total)}\n"
        )
        cases.append(("text invoice", "inv.txt", text.encode(), money(total), date))
    for i in range(4):  # dropped decimal point, the failure mode in the README
        total = round(rng.uniform(100, 3000), 2)
        date = f"{rng.randint(1, 28):02d}/{rng.randint(1, 12):02d}/2026"
        text = (
            f"INVOICE\nInvoice Number: INV-2026-{rng.randint(1000, 9999)}\nFrom: Northwind Supplies Ltd\n"
            f"Invoice Date: {date}\nSubtotal: {money(total)}\nTotal: ${int(round(total * 100))}\n"
        )
        cases.append(("dropped decimal", "inv.txt", text.encode(), money(total), date))
    for i in range(4):  # total missing
        sub = round(rng.uniform(100, 3000), 2)
        date = f"{rng.randint(1, 28):02d}/{rng.randint(1, 12):02d}/2026"
        text = f"INVOICE\nInvoice Number: INV-2026-{rng.randint(1000, 9999)}\nInvoice Date: {date}\nSubtotal: {money(sub)}\nTotal: TBC\n"
        cases.append(("total missing", "inv.txt", text.encode(), money(sub * 1.1), date))
    variants = [("clean", {}), ("downscaled 0.6", {"scale": 0.6}), ("downscaled 0.4", {"scale": 0.4}), ("blurred", {"blur": 1.5})]
    for name, kw in variants:
        for i in range(3):
            total = round(rng.uniform(5, 200), 2)
            date = f"{rng.randint(1, 28):02d}/{rng.randint(1, 12):02d}/2026"
            lines = ["CORNER CAFE", f"Receipt No: R-{rng.randint(10000, 99999)}", f"Date: {date}",
                     f"Item A          {money(total / 2)}", f"Item B          {money(total - round(total / 2, 2))}",
                     f"Total: {money(total)}", "Thank you"]
            cases.append((f"receipt image, {name}", "r.png", render_png(lines, **kw), money(total), date))
    return cases


def main():
    groups = {}
    for label, fn, data, t_total, t_date in build_cases():
        d = process_document(fn, data)
        f = {x["name"]: x["value"] for x in d.fields}
        total_ok = (f.get("total_amount") or "") == t_total
        date_ok = (f.get("invoice_date") or f.get("date") or "") == t_date
        g = groups.setdefault(label, {"n": 0, "total_ok": 0, "date_ok": 0, "wrong": 0, "wrong_flagged": 0, "flagged": 0})
        g["n"] += 1
        g["total_ok"] += total_ok
        g["date_ok"] += date_ok
        g["flagged"] += d.needs_review
        if not (total_ok and date_ok):
            g["wrong"] += 1
            g["wrong_flagged"] += d.needs_review

    tot = {k: sum(g[k] for g in groups.values()) for k in ("n", "total_ok", "date_ok", "wrong", "wrong_flagged", "flagged")}
    silent = tot["wrong"] - tot["wrong_flagged"]
    out = [
        "# Evaluation results", "",
        "Generated by `python eval/run_eval.py`. Seeded (42), documents generated with known ground truth, "
        "run through the real pipeline including Tesseract for the image cases.", "",
        "| Document group | n | Total correct | Date correct | Wrong docs | Wrong and flagged for review |",
        "|---|---|---|---|---|---|",
    ]
    for label, g in groups.items():
        out.append(f"| {label} | {g['n']} | {g['total_ok']}/{g['n']} | {g['date_ok']}/{g['n']} | {g['wrong']} | {g['wrong_flagged']}/{g['wrong']} |")
    out += [
        f"| **All** | {tot['n']} | {tot['total_ok']}/{tot['n']} | {tot['date_ok']}/{tot['n']} | {tot['wrong']} | {tot['wrong_flagged']}/{tot['wrong']} |",
        "", f"**Silent errors (wrong value, not flagged for review): {silent} of {tot['n']} documents.**", "",
        "## Reading these numbers honestly", "",
        "- Documents are synthetic and templated, so accuracy on real, messy documents will be lower. "
        "The useful number is the silent-error count, not the accuracy.",
        "- Only the total and the date are scored. Vendor, merchant and CV fields are heuristic and are expected to "
        "be wrong more often; they carry low confidence so they get reviewed.",
        f"- Review volume: {tot['flagged']} of {tot['n']} documents were flagged, of which "
        f"{tot['flagged'] - tot['wrong_flagged']} had a correct total and date (flagged because a weaker field, "
        "such as the merchant name, scored below the threshold).", "",
    ]
    (ROOT / "RESULTS.md").write_text("\n".join(out))
    print("\n".join(out))
    if silent:
        sys.exit(1)


if __name__ == "__main__":
    main()
